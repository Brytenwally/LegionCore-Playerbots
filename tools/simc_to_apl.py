def read_parts(path):
    parts = {}
    if os.path.isdir(path):
        for name in sorted(os.listdir(path)):
            if name.endswith(".simc"):
                with open(os.path.join(path, name), encoding="utf-8", errors="replace") as f:
                    parts[name[:-5]] = f.read().splitlines()
        return parts
    current = None
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f.read().splitlines():
            m = re.match(r"^### FILE: (.+)\.simc\s*$", line)
            if m:
                current = m.group(1)
                parts[current] = []
            elif current is not None and not line.startswith("###"):
                parts[current].append(line)
    return parts

def keep(line):
    line = line.strip()
    return line.startswith("talents=") or line.startswith("spec=") or re.match(r"^actions(\.[a-z_0-9]+)?\+?=", line)

def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 1
    parts = read_parts(sys.argv[1])
    out_dir = os.path.join(ROOT, "apl")
    os.makedirs(out_dir, exist_ok=True)
    profiles = []
    for name, (spec_id, short) in sorted(SPECS.items(), key=lambda kv: kv[1][0]):
        lines = parts.get(name)
        if lines is None:
            print("missing profile:", name)
            continue
        kept = [l.strip() for l in lines if keep(l)]
        talents = next((l[len("talents="):] for l in kept if l.startswith("talents=")), "")
        actions = [l for l in kept if l.startswith("actions")]
        with open(os.path.join(out_dir, short + ".simc"), "w", encoding="utf-8", newline="\n") as f:
            f.write("# %s (from SimulationCraft %s.simc): talents and action lists only\n" % (short, name))
            f.write("spec_id=%d\n" % spec_id)
            f.write("talents=%s\n" % talents)
            for a in actions:
                f.write(a + "\n")
        profiles.append((spec_id, short, talents, actions))
        print("%-24s spec %3d  talents %s  %d action lines" % (short, spec_id, talents, len(actions)))

    def lit(s):
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

    cpp = os.path.join(ROOT, "src", "combat", "AplProfiles.cpp")
    with open(cpp, "w", encoding="utf-8", newline="\n") as f:
        f.write("/*\n * mod-playerbots: rotation profiles built into the module, generated by tools/simc_to_apl.py from\n")
        f.write(" * SimulationCraft's T21 profiles (the default one of each spec). Do not edit by hand: edit apl/*.simc\n")
        f.write(" * or regenerate. A Playerbots.Rotation.Directory folder overrides them at startup.\n */\n\n")
        f.write('#include "BotApl.h"\n\nnamespace BotApl\n{\n')
        for spec_id, short, talents, actions in profiles:
            f.write("    static char const* const Lines_%d[] =\n    {\n" % spec_id)
            for a in actions:
                f.write("        %s,\n" % lit(a))
            f.write("        nullptr\n    };\n\n")
        f.write("    BuiltInProfile const BuiltInProfiles[] =\n    {\n")
        for spec_id, short, talents, actions in profiles:
            f.write('        { %d, %s, %s, Lines_%d },\n' % (spec_id, lit(short), lit(talents), spec_id))
        f.write("        { 0, nullptr, nullptr, nullptr }\n    };\n}\n")
    print("wrote", cpp)
    return 0

if __name__ == "__main__":
    sys.exit(main())
