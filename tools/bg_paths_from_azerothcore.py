#!/usr/bin/env python3
"""
Extracts the battleground waypoint paths of AzerothCore's mod-playerbots (BattleGroundTactics.cpp, from vmangos) into
src/pvp/BotBattlegroundPaths.cpp of this module.

Usage: tools/bg_paths_from_azerothcore.py <mod-playerbots>/src/Ai/Base/Actions/BattleGroundTactics.cpp

The maps of these battlegrounds are the same on 7.3.5, so the coordinates are kept as they are. Each path is a list of
points; paths listed in vPaths_NoReverseAllowed (jumps down) may only be walked forwards.
"""

import re
import sys
from pathlib import Path

MAPS = {"WS": (489, "Warsong Gulch"), "AB": (529, "Arathi Basin"), "AV": (30, "Alterac Valley"),
        "EY": (566, "Eye of the Storm"), "IC": (628, "Isle of Conquest")}


def main():
    source = Path(sys.argv[1]).read_text(encoding="utf-8")
    point = re.compile(r"\{\s*(-?[\d.]+)f?\s*,\s*(-?[\d.]+)f?\s*,\s*(-?[\d.]+)f?\s*,\s*nullptr\s*\}")

    paths = {}
    for match in re.finditer(r"BattleBotPath\s+(vPath_\w+)\s*=\s*\{(.*?)\};", source, re.S):
        points = [(float(x), float(y), float(z)) for x, y, z in point.findall(match.group(2))]
        if points:
            paths[match.group(1)] = points

    def listed(name):
        block = re.search(r"std::vector<BattleBotPath\*>\s+const\s+" + name + r"\s*=\s*\{(.*?)\};", source, re.S)
        return re.findall(r"&(vPath_\w+)", block.group(1)) if block else []

    one_way = set(listed("vPaths_NoReverseAllowed"))

    out = [
        "/*",
        " * mod-playerbots: battleground waypoint paths. GENERATED by tools/bg_paths_from_azerothcore.py from AzerothCore's",
        " * mod-playerbots (BattleGroundTactics.cpp, paths from vmangos); do not edit by hand.",
        " */",
        "",
        '#include "BotBattlegroundPaths.h"',
        "",
        "namespace BotBattleground",
        "{",
        "    std::vector<BattlegroundPath> const& PathsOfMap(uint32 mapId)",
        "    {",
        "        static std::vector<BattlegroundPath> const none;",
    ]
    total = 0
    for key, (map_id, name) in MAPS.items():
        names = listed("vPaths_" + key)
        out.append("        // " + name)
        out.append("        static std::vector<BattlegroundPath> const map%d =" % map_id)
        out.append("        {")
        for path_name in names:
            points = paths.get(path_name)
            if not points:
                continue
            total += 1
            text = ", ".join("{ %.3ff, %.3ff, %.3ff }" % p for p in points)
            out.append("            { %s, { %s } },  // %s" % ("true" if path_name in one_way else "false", text, path_name[6:]))
        out.append("        };")
        out.append("        if (mapId == %d)" % map_id)
        out.append("            return map%d;" % map_id)
    out.append("        return none;")
    out.append("    }")
    out.append("}")
    target = Path(__file__).resolve().parent.parent / "src" / "pvp" / "BotBattlegroundPaths.cpp"
    target.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print("%d paths written to %s" % (total, target))


if __name__ == "__main__":
    main()
